const makeWaveform = (seed: number): number[] =>
  Array.from({ length: 48 }, (_, i) => {
    const wave = Math.sin((i + seed) * 0.45) * 32 + Math.cos((i * 2 + seed) * 0.8) * 18 + 48;
    return Math.max(14, Math.min(98, Math.round(wave)));
  });

